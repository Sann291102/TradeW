/**
 * The normalized fundamental-research domain.
 *
 * ── THE ONE RULE ───────────────────────────────────────────────────────────
 *
 * Every type in this file is shaped so that "we do not have this number" is
 * REPRESENTABLE and "we have a made-up number" is NOT. Concretely:
 *
 *   · A missing metric is an ABSENT key, never `0` and never `null` masquerading
 *     as a value. Consumers must branch on presence.
 *   · Every present value carries its own provenance — where it came from, when
 *     the vendor stamped it, when we fetched it, and whether the vendor reported
 *     it or we derived it.
 *   · A whole section that could not be retrieved is a discriminated union with
 *     no data field at all (`FundamentalsSection`), so there is nowhere for a
 *     placeholder to live.
 *
 * This exists because the surface it feeds — `/research` — previously rendered
 * hardcoded P/E, ROE, EPS and shareholding figures identically for every symbol,
 * plus an "AI summary" generated by nothing. The fix is not vigilance; it is a
 * type system in which the old page could not have compiled.
 *
 * ── WHY THIS LIVES IN packages/market-data ─────────────────────────────────
 *
 * Same reason the Dhan, Binance and Twelve Data clients do: it is a provider
 * contract plus pure normalization, consumed by a runtime (`services/api`)
 * rather than being one. ARCHITECTURE.md §6 — shared libraries in `packages/`,
 * runtimes in `services/`.
 */

/** Which statement a fact belongs to. */
export type StatementType = 'income' | 'balance' | 'cash_flow';

/** Reporting cadence. Vendors expose both; not every issuer files both. */
export type PeriodType = 'annual' | 'quarterly';

/**
 * Did the vendor report this number, or did we compute it?
 *
 * Load-bearing, not decorative: "Free Cash Flow = Operating Cash Flow − CapEx"
 * is a defensible derivation, but a reader comparing our FCF against an annual
 * report needs to know it was not lifted from one. The UI labels derived rows.
 */
export type ValueBasis = 'reported' | 'derived';

/** Where a number came from and when — attached to every single value. */
export interface Provenance {
  /** Vendor/system id, e.g. 'twelvedata'. Never a human-facing label. */
  source: string;
  /**
   * The vendor's own timestamp for the datum (filing date, statement period end,
   * quote time). Null when the vendor publishes none — which is itself
   * information, and is shown as "vendor published no timestamp" rather than
   * being backfilled with `fetchedAt`.
   */
  sourceTimestamp: string | null;
  /** When THIS system retrieved it. Always known. */
  fetchedAt: string;
}

/**
 * One financial-statement line item for one period.
 *
 * `value` is a plain number in `currency` units (not paise/cents) — statement
 * magnitudes exceed nothing JS floats cannot hold at the precision vendors
 * publish, and rendering rounds anyway. The DB column is a Decimal; this is the
 * transport shape.
 */
export interface FinancialFact {
  metric: string;
  value: number;
  currency: string;
  basis: ValueBasis;
  provenance: Provenance;
}

/** One reporting period's worth of facts for one statement. */
export interface StatementPeriod {
  /** Fiscal year the period belongs to, per the vendor. */
  fiscalYear: number;
  /** 1-4 for quarterly periods; absent for annual. */
  fiscalQuarter?: number;
  /** ISO date of period end. The label the UI sorts and captions by. */
  periodEnd: string;
  periodType: PeriodType;
  currency: string;
  /**
   * Metric -> fact. ABSENT KEY means the vendor did not publish that line for
   * this period. There is deliberately no "0 means missing" convention.
   */
  facts: Record<string, FinancialFact>;
}

/** A complete statement across periods, newest first. */
export interface FinancialStatement {
  statementType: StatementType;
  periodType: PeriodType;
  symbol: string;
  periods: StatementPeriod[];
}

/**
 * Company identity and the slow-moving descriptive fields.
 *
 * Everything optional except symbol/exchange, because vendors' coverage of
 * sector/industry/employees is genuinely patchy outside large caps, and an
 * absent industry must render as absent rather than as "—" pretending to be a
 * value the company does not have.
 */
export interface CompanyProfile {
  symbol: string;
  exchange: string;
  name: string;
  currency: string;
  sector?: string;
  industry?: string;
  country?: string;
  isin?: string;
  website?: string;
  employees?: number;
  description?: string;
  provenance: Provenance;
}

/**
 * Point-in-time market statistics.
 *
 * Deliberately NOT merged into `CompanyProfile`: these move every session and
 * the profile does not, so they carry a separate provenance stamp and the UI
 * can show two different "as of" times honestly instead of one averaged lie.
 */
export interface CompanyStatistics {
  symbol: string;
  currency: string;
  marketCap?: number;
  enterpriseValue?: number;
  sharesOutstanding?: number;
  floatShares?: number;
  fiftyTwoWeekHigh?: number;
  fiftyTwoWeekLow?: number;
  beta?: number;
  dividendYield?: number;
  /**
   * Vendor-published trailing/forward P/E. Kept separate from the ratios we
   * compute ourselves (`ratios.ts`) so the UI can show ours, the vendor's, or
   * both, and never silently present one as the other. Forward P/E is passed
   * through ONLY when the vendor publishes it — this system has no earnings
   * estimates of its own and will not invent a forward number.
   */
  vendorTrailingPe?: number;
  vendorForwardPe?: number;
  vendorPegRatio?: number;
  provenance: Provenance;
}

/** A single holder or holder-category slice of the register. */
export interface OwnershipSlice {
  /** e.g. 'Promoters', 'Institutions', 'Insiders', or a named holder. */
  holder: string;
  /** Percentage of shares outstanding, 0-100. */
  percent: number;
  /** Share count where the vendor publishes one. */
  shares?: number;
}

export interface OwnershipBreakdown {
  symbol: string;
  /** ISO date the register was measured. Never inferred from fetch time. */
  asOf: string | null;
  categories: OwnershipSlice[];
  topHolders: OwnershipSlice[];
  provenance: Provenance;
}

/** Revenue/operating income split by business line or geography. */
export interface SegmentBreakdown {
  symbol: string;
  dimension: 'business' | 'geography';
  periodEnd: string;
  currency: string;
  rows: Array<{
    name: string;
    revenue?: number;
    operatingIncome?: number;
  }>;
  provenance: Provenance;
}

/** A symbol-search hit. Exchange-aware, because 'INFY' exists on NSE and NYSE. */
export interface SymbolSearchHit {
  symbol: string;
  name: string;
  exchange: string;
  micCode?: string;
  country?: string;
  currency?: string;
  instrumentType?: string;
}

/**
 * The typed failure for this whole subsystem.
 *
 * Mirrors `FxDataUnavailableError` and `DhanFault`: a named error the calling
 * service maps to a 503-with-reason, so the UI can say WHY nothing is shown.
 * `detail` is safe to surface to users — it must never carry the API key, and
 * the provider is responsible for keeping it that way.
 */
export class FundamentalsUnavailableError extends Error {
  readonly detail: string;
  constructor(detail: string) {
    super(`Fundamental data is unavailable (${detail})`);
    this.name = 'FundamentalsUnavailableError';
    this.detail = detail;
  }
}

/**
 * The provider port.
 *
 * Every method either RESOLVES with real vendor data or THROWS
 * `FundamentalsUnavailableError`. There is no third outcome — in particular no
 * "empty but successful" result that a caller could mistake for "this company
 * has no revenue". A vendor that genuinely returns an empty statement list is
 * an unavailability, and providers must raise it as one.
 */
export interface FinancialDataProvider {
  readonly name: string;
  searchSymbols(query: string, limit: number): Promise<SymbolSearchHit[]>;
  getProfile(symbol: string): Promise<CompanyProfile>;
  getStatistics(symbol: string): Promise<CompanyStatistics>;
  getStatement(symbol: string, type: StatementType, periodType: PeriodType): Promise<FinancialStatement>;
  /** Optional coverage — providers that do not publish it throw. */
  getOwnership(symbol: string): Promise<OwnershipBreakdown>;
  /** Optional coverage — providers that do not publish it throw. */
  getSegments(symbol: string): Promise<SegmentBreakdown[]>;
  healthCheck(): Promise<boolean>;
}

