/** Ordered line specs the UI renders, per statement. Order IS the presentation
 *  contract — a P&L that lists net income above revenue is wrong even if every
 *  number is right — so it lives here beside the vocabulary rather than in a
 *  component. `total` marks subtotal rows the UI emphasises; `indent` nests. */
export interface StatementLineSpec {
  metric: string;
  label: string;
  total?: boolean;
  indent?: boolean;
  /** Section heading rendered above this line. */
  section?: string;
}

